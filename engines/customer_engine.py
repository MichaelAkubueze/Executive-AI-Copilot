import pandas as pd
import plotly.express as px

def customer_chart_layout(fig):

    fig.update_layout(
        template="plotly_white",
        height=420,
        margin=dict(
            l=40,
            r=40,
            t=70,
            b=40
        ),
        legend=dict(
            orientation="h",
            yanchor="bottom",
            y=1.02,
            xanchor="right",
            x=1
        )
    )

    return fig
