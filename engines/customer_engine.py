# HIGH-VALUE CUSTOMERS
# ==========================================================

def high_value_customers(df, limit=20):

    customer_summary = (
        df.groupby(
            "Customer Name",
            as_index=False
        )
        .agg(
            Orders=("Order ID", "nunique"),
            Revenue=("Revenue", "sum"),
            Profit=("Profit", "sum"),
        )
        .sort_values(
            "Revenue",
            ascending=False
        )
        .head(limit)
        .reset_index(drop=True)
    )

    customer_summary.insert(
        0,
        "Rank",
        range(
            1,
            len(customer_summary) + 1
        )
    )

    return customer_summary


# ==========================================================
# AT-RISK CUSTOMERS
# ==========================================================

def at_risk_customers(df, limit=20):

    customer_summary = (
        df.groupby(
            "Customer Name",
            as_index=False
        )
        .agg(
            Orders=("Order ID", "nunique"),
            Revenue=("Revenue", "sum"),
            Profit=("Profit", "sum"),
        )
    )

    customer_summary["Profit Margin"] = (
        customer_summary["Profit"]
        / customer_summary["Revenue"]
        * 100
    )

    # Customers with only one order are treated as
    # potential retention opportunities.

    at_risk = (
        customer_summary[
            customer_summary["Orders"] == 1
        ]
        .sort_values(
            "Revenue",
            ascending=False
        )
        .head(limit)
        .reset_index(drop=True)
    )

    at_risk.insert(
        0,
        "Rank",
        range(
            1,
            len(at_risk) + 1
        )
    )

    return at_risk
