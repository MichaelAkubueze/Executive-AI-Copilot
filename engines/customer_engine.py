# CUSTOMER DRILL-DOWN
# ==========================================================

def customer_drilldown(df, customer_name):

    customer_df = df[
        df["Customer Name"] == customer_name
    ].copy()

    if customer_df.empty:
        return None

    total_revenue = customer_df["Revenue"].sum()

    total_profit = customer_df["Profit"].sum()

    orders = customer_df["Order ID"].nunique()

    products = customer_df["Product Name"].nunique()

    regions = customer_df["Region"].nunique()

    margin = (
        total_profit / total_revenue * 100
        if total_revenue != 0
        else 0
    )

    return {
        "Revenue": total_revenue,
        "Profit": total_profit,
        "Orders": orders,
        "Products": products,
        "Regions": regions,
        "Margin": margin,
    }


