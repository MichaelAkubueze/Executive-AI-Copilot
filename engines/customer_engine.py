def new_vs_returning_revenue_chart(df):

    customer_orders = (
        df.groupby("Customer ID")
        .agg(
            Orders=("Order ID", "nunique"),
            Revenue=("Revenue", "sum"),
        )
        .reset_index()
    )

    customer_orders["Customer Type"] = (
        customer_orders["Orders"]
        .apply(
            lambda x:
            "New Customer"
            if x == 1
            else "Returning Customer"
        )
    )

    summary = (
        customer_orders
        .groupby(
            "Customer Type",
            as_index=False
        )
        .agg(
            Revenue=("Revenue", "sum")
        )
    )

    fig = px.bar(
        summary,

        x="Customer Type",

        y="Revenue",

        color="Customer Type",

        title="New vs Returning Customer Revenue",
    )

    return customer_chart_layout(fig)
