# CUSTOMER KPI ENGINE
# ==========================================================

def total_customers(df):
    """Return the number of unique customers."""

    return df["Customer ID"].nunique()


def total_customer_revenue(df):
    """Return total revenue generated by customers."""

    return df["Revenue"].sum()


def total_customer_profit(df):
    """Return total profit generated by customers."""

    return df["Profit"].sum()


def average_customer_revenue(df):
    """Return average revenue per unique customer."""

    customers = df["Customer ID"].nunique()

    if customers == 0:
        return 0

    return df["Revenue"].sum() / customers


def average_customer_profit(df):
    """Return average profit per unique customer."""

    customers = df["Customer ID"].nunique()

    if customers == 0:
        return 0

    return df["Profit"].sum() / customers


def customer_orders(df):
    """Return total number of customer transactions."""

    return len(df)


def customer_purchase_frequency(df):
    """Return average number of transactions per customer."""

    customers = df["Customer ID"].nunique()

    if customers == 0:
        return 0

    return len(df) / customers


def customer_profit_margin(df):
    """Return overall customer profit margin."""

    revenue = df["Revenue"].sum()

    if revenue == 0:
        return 0

    return df["Profit"].sum() / revenue

