def new_vs_returning_customers_chart(df):

    customer_orders = (
        df.groupby("Customer ID")
        .agg(
            Orders=("Order ID", "nunique")
        )
        .reset_index()
    )

    customer_orders["Customer Type"] = (
        customer_orders["Orders"]
        .apply(
            lambda x:
            "New Customer"
            if x == 1
            else "Returning Customer"
        )
    )

    summary = (
        customer_orders
        .groupby(
            "Customer Type",
            as_index=False
        )
        .agg(
            Customers=("Customer ID", "count")
        )
    )

    fig = px.pie(
        summary,

        names="Customer Type",

        values="Customers",

        hole=0.55,

        title="New vs Returning Customers",
    )

    fig.update_traces(
        textposition="inside",

        textinfo="percent+label",
    )

    return customer_chart_layout(fig)

