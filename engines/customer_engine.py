# NEW VS RETURNING CUSTOMERS
# ==========================================================

def new_customers(df):

    customer_orders = (
        df.groupby("Customer ID")
        .agg(
            FirstPurchase=("Order Date", "min"),
            Orders=("Order ID", "nunique"),
        )
        .reset_index()
    )

    return (
        customer_orders["Orders"] == 1
    ).sum()


def returning_customers(df):

    customer_orders = (
        df.groupby("Customer ID")
        .agg(
            Orders=("Order ID", "nunique"),
        )
        .reset_index()
    )

    return (
        customer_orders["Orders"] > 1
    ).sum()


def repeat_customer_rate(df):

    customers = df["Customer ID"].nunique()

    if customers == 0:
        return 0

    returning = returning_customers(df)

    return returning / customers * 100

